import AppKit
import ImageIO
import UniformTypeIdentifiers

/// 剪贴板监控 — 每 `pollingInterval` 秒检查 NSPasteboard.changeCount
@MainActor
final class ClipboardMonitor: ObservableObject {
    /// 轮询间隔（秒）。500ms 是 Raycast / Paste / Maccy 等同类工具的常见取舍：
    /// 更短会增加唤醒频率和电量消耗，更长会让"刚复制立即唤起"产生肉眼可感的延迟。
    private static let pollingInterval: TimeInterval = 0.5

    /// 单条文本最大字节数（10MB）。超过时跳过持久化：
    /// 大文本通常是终端 dump、整本 PDF 文本提取等极端场景；10MB 能覆盖绝大多数"我真想保存"的长文本，
    /// 同时防止个别极端条目把 DB 撑大、拖慢 FTS 重建。
    private static let maxTextBytes = 10 * 1024 * 1024

    private enum PasteboardMetadata {
        static let sourceBundleID = NSPasteboard.PasteboardType("org.nspasteboard.source")
        static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
        static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

        static let sensitiveTypes: Set<NSPasteboard.PasteboardType> = [
            concealed,
            transient,
            autoGenerated
        ]
    }

    private enum ClipboardPayload: Sendable {
        case text(String, String?, String?, [ClipboardRepresentation])
        case url(String, String?, String?, [ClipboardRepresentation])
        case file([URL], String, String?, String?, [ClipboardRepresentation])
        /// 图片数据延迟到 detached task 内通过 MainActor.run 拉取：避免 500ms timer 主线程
        /// 同步读 TIFF（截图原图可数 MB）卡 UI；用 captured changeCount 防止读到下一次复制的数据。
        /// 辅助 reps（file-url/html/url 等）也在后台 hop 主线程时一起读，保持单次 pasteboard 快照一致性。
        case imageLazy(changeCount: Int, sourceApp: String?, sourceName: String?)
    }

    private let core: ClipinCore
    private let settings: SettingsStore
    /// 轮询在后台队列执行：500ms 主线程 Timer 会让常驻 app 每秒醒两次主线程，
    /// 即使剪贴板几小时没变化也照醒。后台队列只读 changeCount，变化才 hop 主线程，
    /// 主线程唤醒次数从「固定 2 次/秒」降到「实际复制时 1 次」。
    /// NSPasteboard 只在这一处后台访问，且只碰 changeCount 这个标量；
    /// 其余 pasteboard 读取仍全部在主线程，把跨线程面收敛到最小。
    private let pollQueue = DispatchQueue(label: "com.ccfco.Clipin.clipboard-poll", qos: .utility)
    private var pollTimer: DispatchSourceTimer?
    /// isPaused / lastChangeCount 同时被主线程（pause/resume/init）和轮询队列访问。
    /// `nonisolated(unsafe)`：这两个值和 stateLock 是同一组手工加锁的状态，
    /// 所有读写都已在锁内完成。Swift 的 actor 隔离无法表达「跨线程 + NSLock」，
    /// 用 nonisolated(unsafe) 把保证责任显式落到这里，避免把整个轮询路径搬上主线程。
    private nonisolated(unsafe) let stateLock = NSLock()
    private nonisolated(unsafe) var lastChangeCount: Int
    private nonisolated(unsafe) var isPaused = false
    /// 持有所有正在跑的 persist task，stop() 时统一取消。
    /// 旧实现 Task.detached 启动后没有持有引用，监控停止/进程退出时正在跑的图片 OCR
    /// 仍会继续 Vision 调用并发通知，破坏 launcher 关闭后"什么都不再变"的语义。
    /// 取消不会 abort 已经开始的 SQLite write，但 OCR 段（recognizeText）会响应。
    private var inflightPersists: Set<Task<Void, Never>> = []

    init(core: ClipinCore, settings: SettingsStore) {
        self.core = core
        self.settings = settings
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        guard pollTimer == nil else { return }
        let timer = DispatchSource.makeTimerSource(queue: pollQueue)
        // leeway 100ms：允许系统合并唤醒，常驻进程省电；对「复制后立即唤起」的
        // 体感无影响（主线程只在 changeCount 真的变了才被叫醒）。
        timer.schedule(
            deadline: .now() + Self.pollingInterval,
            repeating: Self.pollingInterval,
            leeway: .milliseconds(100)
        )
        // 显式 @Sendable：不标注时闭包会继承 start() 的 @MainActor 隔离，
        // 在轮询队列执行时会触发 "dispatch_assert_queue" 运行时断言（实测崩溃）。
        timer.setEventHandler { @Sendable [weak self] in
            self?.pollOnBackground()
        }
        timer.resume()
        pollTimer = timer
    }

    func stop() {
        pollTimer?.cancel()
        pollTimer = nil
        let pending = inflightPersists
        inflightPersists.removeAll()
        pending.forEach { $0.cancel() }
    }

    /// 暂停监控（粘贴时用，避免把自己写入的内容又存一遍）
    func pause() {
        stateLock.lock()
        isPaused = true
        stateLock.unlock()
    }

    /// 恢复监控，跳过暂停期间的变化
    func resume() {
        // 先在锁外读 pasteboard（跨进程 IPC，不占用轮询队列的状态锁），再原子落状态。
        let current = NSPasteboard.general.changeCount
        stateLock.lock()
        lastChangeCount = current
        isPaused = false
        stateLock.unlock()
    }

    var onNewItem: (() -> Void)?

    /// 后台轮询：只读 changeCount，变化时把具体处理交回主线程。
    /// 主线程已经通过 resume() 对齐过 lastChangeCount，这里的重复更新是安全的。
    nonisolated private func pollOnBackground() {
        stateLock.lock()
        let paused = isPaused
        stateLock.unlock()
        guard !paused else { return }

        let currentCount = NSPasteboard.general.changeCount

        stateLock.lock()
        let changed = currentCount != lastChangeCount
        if changed { lastChangeCount = currentCount }
        stateLock.unlock()

        guard changed else { return }
        Task { @MainActor [weak self] in
            self?.checkClipboard(changeCount: currentCount)
        }
    }

    private func checkClipboard(changeCount currentCount: Int) {
        guard !isPaused else { return }
        // 后台已经确认 changeCount 变了；主线程不再重复读，避免两次读取之间
        // 又被别的 app 改写时把「不是本次变化」的内容记进来。
        let pasteboard = NSPasteboard.general
        // 后台判定与主线程处理之间用户可能又复制了一次：当前 pasteboard 已不是
        // 后台看到的那一版。本次直接放弃，下一次轮询会按新 changeCount 处理最新内容。
        guard pasteboard.changeCount == currentCount else { return }

        guard shouldPersistContents(of: pasteboard) else { return }

        let source = resolveSourceApp(from: pasteboard)
        let sourceApp = source.bundleIdentifier
        let sourceName = source.appName

        // 判定顺序：image → file → url → text
        // image flavor ≠「用户复制的是图片」。读 per-item 结构(pasteboardItems)而非扁平
        // pasteboard.types 来还原真相：Finder 复制文件/文件夹时，file-url 和它的图标
        // (com.apple.icns) 在同一个 NSPasteboardItem 里——系统已明确标注「这图是这个文件的图标」，
        // 不是独立图片内容；扁平 types 把它们拍平、还从 icns 合成幻影 public.tiff，旧逻辑「有
        // image flavor 就当图片」因此把 zip/文件夹/文档误判成「图片·访达 (1024×1024)」。
        // 不变量(全部 per-item 结构事实，零文件系统探测)：
        // - 「无 file-url 但有真实图片(排除 icns 图标)」的 item = 纯图片内容(截图) → image
        // - 恰好单个文件项且它自带真实图片 = 复制单个图片文件 / iPhone 隔空复制图片 → image(可回放)
        // - 其余有 file-url 的情况(文件夹/zip/文档，单个或多选混图) → file(保留完整文件集合)
        let items = pasteboard.pasteboardItems ?? []
        let fileItems = items.filter(Self.itemHasFileURL)
        let fileItemCount = fileItems.count
        let singleFileItemIsImage = fileItemCount == 1 && Self.itemHasRealImage(fileItems[0])
        let hasPureImageItem = items.contains { !Self.itemHasFileURL($0) && Self.itemHasRealImage($0) }
        let fileURLs = (pasteboard.readObjects(forClasses: [NSURL.self], options: [
            .urlReadingFileURLsOnly: true
        ]) as? [URL]) ?? []

        if Self.shouldTreatAsImage(
            fileItemCount: fileItemCount,
            singleFileItemIsImage: singleFileItemIsImage,
            hasPureImageItem: hasPureImageItem
        ) {
            // 不在这里同步读数据：types 探测廉价，timer 立即返回；data 由后台任务通过
            // MainActor.run 拉，主线程读取还在但不再占用 timer 触发那一帧
            persist(.imageLazy(changeCount: currentCount, sourceApp: sourceApp, sourceName: sourceName))
        } else if !fileURLs.isEmpty {
            let paths = fileURLs.map(\.path)
            // file 类型不能把 image bytes 塞进 clip_representations.data；图片文件的可回放缓存
            // 统一走 attachment_paths -> imageDir PNG。其他非 image UTI 仍可作为辅助表达保留。
            let reps = ClipboardRepresentationExtractor
                .extractAuxiliary(from: pasteboard, primaryClipType: .file)
                .filter { !Self.isImageContentType(NSPasteboard.PasteboardType($0.uti)) }
            persist(.file(fileURLs, FileClipboardContent.encodedContent(from: paths), sourceApp, sourceName, reps))
        } else if let urlString = pasteboard.string(forType: .URL) ?? extractURL(from: pasteboard) {
            let reps = ClipboardRepresentationExtractor.extract(from: pasteboard, primaryContent: urlString)
            persist(.url(urlString, sourceApp, sourceName, reps))
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty {
            // 超大文本（终端 dump、整本电子书等）跳过：FTS 重建会卡，磁盘也会被吃光
            if text.utf8.count > Self.maxTextBytes {
                ClipinLog.monitor.notice("Skipped clipboard text larger than \(Self.maxTextBytes, privacy: .public) bytes")
                return
            }
            let reps = ClipboardRepresentationExtractor.extract(from: pasteboard, primaryContent: text)
            persist(.text(text, sourceApp, sourceName, reps))
        }
    }

    private func persist(_ payload: ClipboardPayload) {
        let core = self.core

        // 自引用 box：task body 完成时回主线程从 inflightPersists 移除自己，避免集合无限增长。
        // 用 Box<Task?> 是因为 Task 创建时还没拿到自身引用——先建 box、Task 内闭包持有 box、
        // Task 创建后写入 box，闭包 defer 时通过 box 拿到 task 引用。
        // `finished` 兜住反向竞态：极快的任务可能在 box.task 赋值前就跑到 defer，
        // 此时拿不到 task 会漏移除，集合随复制次数单调增长（常驻数周即泄漏）。
        // defer 与赋值都在主线程串行，finished 由双方检查即可闭合两种顺序。
        let box = TaskBox()
        let task = Task.detached(priority: .utility) { [weak self] in
            defer {
                // 显式把 weak self 重新 capture 进 inner Task：Swift 6 严格 isolation 下
                // 直接在 detached body 的 defer 里捕获外层 weak self 会被判为跨 actor
                // 边界 send 引用（即使 Monitor 是 @MainActor 也不行）。重 capture 后就是
                // 一次普通的 MainActor 任务调度。
                let monitor = self
                Task { @MainActor in
                    box.finished = true
                    guard let task = box.task else { return }
                    monitor?.inflightPersists.remove(task)
                }
            }
            do {
                switch payload {
                case let .text(content, sourceApp, sourceName, reps):
                    let coreReps = reps.map { ClipRepresentation(uti: $0.uti, data: $0.data) }
                    _ = try core.saveItemWithRepresentations(
                        content: content,
                        clipType: .text,
                        sourceApp: sourceApp,
                        sourceName: sourceName,
                        imagePath: nil,
                        representations: coreReps
                    )

                case let .url(content, sourceApp, sourceName, reps):
                    let coreReps = reps.map { ClipRepresentation(uti: $0.uti, data: $0.data) }
                    _ = try core.saveItemWithRepresentations(
                        content: content,
                        clipType: .url,
                        sourceApp: sourceApp,
                        sourceName: sourceName,
                        imagePath: nil,
                        representations: coreReps
                    )

                case let .file(urls, content, sourceApp, sourceName, reps):
                    try await self?.persistFile(
                        urls: urls,
                        content: content,
                        sourceApp: sourceApp,
                        sourceName: sourceName,
                        auxReps: reps,
                        core: core
                    )

                case let .imageLazy(capturedChangeCount, sourceApp, sourceName):
                    // 后台任务里 hop 回 main 拉 pasteboard data + 辅助 reps：
                    // 必须在单次 hop 内一起读，确保 image bytes 和 file-url/html 等
                    // 都来自同一个 pasteboard 快照，否则中间用户又复制别的会割裂
                    struct ImageSnapshot {
                        let data: Data
                        let uti: String
                        let reps: [ClipboardRepresentation]
                    }
                    let snapshot: ImageSnapshot? = await MainActor.run {
                        let pb = NSPasteboard.general
                        // 用户已经又复制了别的内容，捕获到的快照已过期，丢弃
                        guard pb.changeCount == capturedChangeCount else { return nil }
                        // 已按 per-item 结构判定为 image，却读不出任何真实图片 bytes：异常路径，
                        // 不静默吞（CLAUDE.md 不兜底红线）。无 bytes 无法落库、也无 file-url 可降级，
                        // 只能丢弃本条，但必须留痕便于排查（如 AirDrop promised data 延迟实体化）。
                        guard let image = Self.readImageData(from: pb) else {
                            ClipinLog.monitor.error("判定为 image 但 pasteboard 读不出图片 bytes，丢弃本条 (changeCount=\(capturedChangeCount, privacy: .public))")
                            return nil
                        }
                        let auxReps = ClipboardRepresentationExtractor.extractAuxiliary(from: pb, primaryClipType: .image)
                        return ImageSnapshot(data: image.data, uti: image.uti, reps: auxReps)
                    }
                    guard let snapshot else { return }
                    if Task.isCancelled { return }
                    try await self?.persistImage(
                        rawData: snapshot.data,
                        sourceUTI: snapshot.uti,
                        sourceApp: sourceApp,
                        sourceName: sourceName,
                        auxReps: snapshot.reps,
                        core: core
                    )
                    return  // persistImage 内自行 notify，跳过下方公共 notifyNewItem

                }

                guard let self else { return }
                await self.notifyNewItem()
            } catch {
                ClipinLog.monitor.error("Failed to persist clipboard item: \(error.localizedDescription, privacy: .public)")
            }
        }
        box.task = task
        inflightPersists.insert(task)
        // 任务若在赋值前已跑完 defer（见上），这里补一次移除。
        if box.finished {
            inflightPersists.remove(task)
        }
    }

    private func shouldPersistContents(of pasteboard: NSPasteboard) -> Bool {
        let types = Set(pasteboard.types ?? [])

        // ConcealedType：密码管理器等明确标记的敏感内容，始终跳过
        if types.contains(PasteboardMetadata.concealed) {
            settings.incrementNoiseSkipped()
            return false
        }

        // TransientType / AutoGeneratedType：临时或自动生成内容，由用户设置决定
        if settings.skipTransientContent {
            let transientTypes: Set<NSPasteboard.PasteboardType> = [
                PasteboardMetadata.transient,
                PasteboardMetadata.autoGenerated,
            ]
            if !types.isDisjoint(with: transientTypes) {
                settings.incrementNoiseSkipped()
                return false
            }
        }

        // Clipin 自己写回的剪贴板内容（粘贴回写）不计入"噪声"，是预期回路
        if let sourceBundleID = pasteboard.string(forType: PasteboardMetadata.sourceBundleID),
           sourceBundleID == Bundle.main.bundleIdentifier {
            return false
        }

        return true
    }

    private func resolveSourceApp(from pasteboard: NSPasteboard) -> (bundleIdentifier: String?, appName: String?) {
        if let bundleIdentifier = pasteboard.string(forType: PasteboardMetadata.sourceBundleID),
           !bundleIdentifier.isEmpty {
            let appName = NSRunningApplication
                .runningApplications(withBundleIdentifier: bundleIdentifier)
                .first?
                .localizedName
            return (bundleIdentifier, appName)
        }

        let tracker = SourceAppTracker.shared
        return (tracker.bundleIdentifier, tracker.appName)
    }

    /// 判断一段文本是否为 http/https URL。是则原样返回（保留大小写与参数），否则 nil。
    /// Edit Content 保存时复用此判据，确保与剪贴板监控的 URL 识别口径一致。
    /// `nonisolated`：纯函数无 actor 状态，需同时被 @MainActor 的 ViewModel 与
    /// nonisolated 的单元测试调用——与下方 `makePNGData` 同一惯例。
    nonisolated static func httpURLString(in text: String) -> String? {
        guard let url = URL(string: text),
              let scheme = url.scheme,
              ["http", "https"].contains(scheme) else { return nil }
        return text
    }

    private func extractURL(from pasteboard: NSPasteboard) -> String? {
        guard let text = pasteboard.string(forType: .string) else { return nil }
        return Self.httpURLString(in: text)
    }

    /// 「image vs file」主类型纯决策。入参由 checkClipboard 从 pasteboardItems 派生，全是
    /// per-item 结构事实，无 IO，便于单测：
    /// - fileItemCount        含 file-url 的 item 数（= 一次复制的文件集合大小）
    /// - singleFileItemIsImage  恰好单个文件项 且 该 item 自带真实图片(隔空复制图片/复制图片文件)
    /// - hasPureImageItem     存在「无 file-url 但有真实图片」的 item（纯截图）
    ///
    /// 文件集合语义优先：只要有 file-url，就按文件集合处理——仅当「恰好一个文件项且它就是图片」
    /// 才升级 image(保 iPhone 隔空可回放)；多选(哪怕混入图片)一律 file，保留完整集合不丢文件。
    /// 没有任何文件项时，纯图片项(截图)才是 image。
    nonisolated static func shouldTreatAsImage(
        fileItemCount: Int,
        singleFileItemIsImage: Bool,
        hasPureImageItem: Bool
    ) -> Bool {
        if fileItemCount >= 1 {
            return fileItemCount == 1 && singleFileItemIsImage
        }
        return hasPureImageItem
    }

    /// 单个 pasteboard item 是否携带 file-url——判定它是「文件引用」而非独立内容的结构信号。
    nonisolated private static func itemHasFileURL(_ item: NSPasteboardItem) -> Bool {
        item.types.contains { $0.rawValue == "public.file-url" }
    }

    /// 单个 pasteboard item 是否携带「真实图片内容」representation（排除 icns 图标）。
    nonisolated private static func itemHasRealImage(_ item: NSPasteboardItem) -> Bool {
        item.types.contains(where: Self.isRealImageType)
    }

    /// 判定单个 UTI 是否「真实图片内容」。在 isImageContentType 基础上额外排除 com.apple.icns：
    /// icns 是文件图标专用格式(conforms public.image 但不是用户复制的图片内容)，Finder 复制
    /// 文件/文件夹时附带，正是把 zip/文件夹误判成图片的根因。用于「是不是图片」的分类与读 bytes。
    nonisolated static func isRealImageType(_ type: NSPasteboard.PasteboardType) -> Bool {
        guard type.rawValue != "com.apple.icns" else { return false }
        return Self.isImageContentType(type)
    }

    /// 从 pasteboard 读出真实图片 bytes(排除 icns)，连同其 UTI 一起返回——调用方
    /// 用 UTI 判断能否跳过「解码再重编码」直接落盘。逐 item 读：含 file-url 的文件项
    /// 只挂 icns 时读不出图，只有截图项 / 自带真实图片的图片文件项能命中。
    /// PNG/TIFF 优先(macOS 原生格式)，其余格式(jpeg/heic/gif/webp 等)由
    /// makePNGData 用 CGImageSource 统一兜底转 PNG。
    nonisolated private static func readImageData(from pasteboard: NSPasteboard) -> (data: Data, uti: String)? {
        let preferred: [NSPasteboard.PasteboardType] = [.png, .tiff]
        for item in pasteboard.pasteboardItems ?? [] {
            for type in preferred where item.types.contains(type) && Self.isRealImageType(type) {
                if let data = item.data(forType: type) { return (data, type.rawValue) }
            }
            for type in item.types where Self.isRealImageType(type) {
                if let data = item.data(forType: type) { return (data, type.rawValue) }
            }
        }
        return nil
    }

    /// 判定单个 UTI 是否表示"图片内容"。public.file-url 显式排除：它自身不 conforms to image，
    /// 但保险起见排除，避免未来 macOS 给 file-url 加 image conformance 时让 file 复制误入图片分支。
    /// 含 com.apple.icns(图标也 conforms image)：用于 file 分支把图标等图片类挡在 representations 外。
    nonisolated private static func isImageContentType(_ type: NSPasteboard.PasteboardType) -> Bool {
        guard type.rawValue != "public.file-url" else { return false }
        guard let utType = UTType(type.rawValue) else { return false }
        return utType.conforms(to: .image)
    }

    /// file-url 保存的主路径：先缓存其中可解码的图片文件，再以 file 类型落库。
    /// 图片缓存失败只影响对应 fallback，不影响原始文件路径记录；粘贴时仍会先试原始 URL。
    nonisolated private func persistFile(
        urls: [URL],
        content: String,
        sourceApp: String?,
        sourceName: String?,
        auxReps: [ClipboardRepresentation],
        core: ClipinCore
    ) async throws {
        let itemID = UUID().uuidString
        var cachedPaths = Array(repeating: "", count: urls.count)
        var dbSaved = false
        // R9 修复：在 DB save 完成前已写盘的 PNG 是孤儿（被 task cancel 或下游 throw
        // 截断时累积）。defer 在所有 return / throw 路径都跑，dbSaved=true 时跳过清理；
        // 否则把本次任务写过的 PNG 全删掉，保证"DB 引用 vs 磁盘文件"二者强一致。
        defer {
            if !dbSaved {
                for path in cachedPaths where !path.isEmpty {
                    try? FileManager.default.removeItem(atPath: path)
                }
            }
        }

        for (index, url) in urls.enumerated() where Self.isImageFileURL(url) {
            do {
                let rawData = try Data(contentsOf: url)
                let pngData = try Self.makePNGData(from: rawData)
                cachedPaths[index] = try core.writeAttachmentPng(
                    itemId: itemID,
                    index: Int32(index),
                    bytes: pngData
                )
            } catch {
                ClipinLog.monitor.error("Failed to cache image file attachment \(url.path, privacy: .private): \(error.localizedDescription, privacy: .public)")
            }
            if Task.isCancelled { return }  // defer 会清理本次已写的 PNG
        }

        let attachmentPaths: String?
        if cachedPaths.contains(where: { !$0.isEmpty }) {
            let data = try JSONEncoder().encode(cachedPaths)
            attachmentPaths = String(data: data, encoding: .utf8)
        } else {
            attachmentPaths = nil
        }

        let coreReps = auxReps.map { ClipRepresentation(uti: $0.uti, data: $0.data) }
        _ = try core.saveItemWithAttachmentPaths(
            itemId: itemID,
            content: content,
            clipType: .file,
            sourceApp: sourceApp,
            sourceName: sourceName,
            imagePath: nil,
            attachmentPaths: attachmentPaths,
            representations: coreReps
        )
        dbSaved = true  // DB 写入成功，defer 不再清理
        // 通知由 persist() 的公共路径统一发出：这里再发一次会让每次文件复制
        // 触发两轮 loadItems + runCleanupAndReload（列表重载与清理都跑两遍）。
    }

    /// 共享的图片入库后处理：原始编码落地 → DB 入库 → 尺寸读写 → 通知 → OCR。
    /// 由 imageLazy（pasteboard 直挂 image bytes）和 imageFromFile（file-url 升级）两个 case 复用，
    /// 仅"原始 bytes 来源"不同，落地后流程完全一致，避免 ~30 行重复。
    /// nonisolated 因为调用方在 detached task 内运行；唯一的主线程依赖（notifyNewItem）
    /// 通过 await 跨 actor 调用——ClipboardMonitor 整体是 @MainActor 类，await 自动 hop。
    nonisolated private func persistImage(
        rawData: Data,
        sourceUTI: String,
        sourceApp: String?,
        sourceName: String?,
        auxReps: [ClipboardRepresentation],
        core: ClipinCore
    ) async throws {
        let imageDir = core.imageDir()
        let (bytes, ext) = try Self.prepareImageBytes(rawData, sourceUTI: sourceUTI)
        let filename = UUID().uuidString + "." + ext
        let path = (imageDir as NSString).appendingPathComponent(filename)
        try bytes.write(to: URL(fileURLWithPath: path), options: .atomic)
        let coreReps = auxReps.map { ClipRepresentation(uti: $0.uti, data: $0.data) }
        let saved = try core.saveItemWithRepresentations(
            content: "image",
            clipType: .image,
            sourceApp: sourceApp,
            sourceName: sourceName,
            imagePath: path,
            representations: coreReps
        )
        // 入库后立即读图片头写回尺寸，让列表首次渲染就带 (宽×高)
        if let size = ImageDimensions.read(at: path) {
            do {
                try core.updateImageDimensions(id: saved.id, width: size.width, height: size.height)
            } catch {
                ClipinLog.imageDimensions.error("图片尺寸写入失败 id=\(saved.id, privacy: .public): \(error.localizedDescription, privacy: .public)")
            }
        }
        // 图片入库后立即刷新列表，让条目即时出现，不等 OCR
        await self.notifyNewItem()
        // stop() 取消后，DB 已经写完不能撤销，但 OCR/通知都跳过，
        // 避免 launcher 关闭后还冒出"OCR 完成"广播
        if Task.isCancelled { return }

        // OCR 在同一后台 Task 内串行执行，完成后二次刷新显示文字
        let itemId = saved.id
        let ocrText = await OcrService.shared.recognizeText(at: path)
        if Task.isCancelled { return }
        do {
            try core.updateOcrText(id: itemId, ocrText: ocrText)
            if !ocrText.isEmpty {
                NotificationCenter.default.post(name: .clipboardItemOcrUpdated, object: nil)
            }
            // 图片要等 OCR 落库后才进入标签候选，这里再踢一次（幂等）。
            await requestAiTagging()
        } catch {
            if case ClipinError.NotFound = error {
                ClipinLog.ocr.info("OCR result discarded: item \(itemId, privacy: .public) was replaced by dedup")
            } else {
                ClipinLog.ocr.error("Failed to write OCR result id=\(itemId, privacy: .public): \(error.localizedDescription, privacy: .public)")
            }
        }
    }

    /// 文件大小上限：超过则不升级为 image，仍按 file 类型采集。
    /// 20MB 覆盖绝大多数手机/相机直出图；超过通常是视频/扫描件巨图——读文件 + makePNGData + OCR
    /// 会吃大量 CPU/内存而收益有限，且 image 主载体在剪贴板上的实用性也下降。
    /// nonisolated：被 isImageFileURL（nonisolated static）引用，类整体 @MainActor 默认会传递。
    nonisolated private static let imageFileSizeLimit: Int64 = 20 * 1024 * 1024

    /// 判定 file-url 是否符合"升级为 image"的条件：本地文件 + 存在 + 是图片扩展名 + 大小不超限。
    /// 用 UTType conformance 判断扩展名而非硬编码白名单，自动覆盖 jpeg/heic/heif/webp 以及未来新格式。
    nonisolated private static func isImageFileURL(_ url: URL) -> Bool {
        guard url.isFileURL else { return false }
        let fm = FileManager.default
        guard fm.fileExists(atPath: url.path) else { return false }
        // 大小上限：防御性约束，避免读巨大文件拖慢采集
        if let attrs = try? fm.attributesOfItem(atPath: url.path),
           let size = attrs[.size] as? NSNumber,
           size.int64Value > Self.imageFileSizeLimit {
            return false
        }
        // 扩展名 → UTType → conforms(to: .image)：覆盖所有 ImageIO 支持的格式
        guard let utType = UTType(filenameExtension: url.pathExtension),
              utType.conforms(to: .image) else {
            return false
        }
        return true
    }

    /// 决定图片落盘字节与扩展名。能无损保留原始编码就保留：JPEG/HEIC 照片转 PNG
    /// 体积会放大 5~10 倍（每条历史一份），同时拖慢备份、缩略图与 OCR 读取。
    /// TIFF 体积过大且剪贴板来源常是截图，统一转 PNG；未知格式同理回退 PNG。
    /// 保留前先确认 ImageIO 能解析容器头部，避免把损坏字节原样写进历史。
    nonisolated private static func prepareImageBytes(
        _ rawData: Data,
        sourceUTI: String
    ) throws -> (Data, String) {
        let preservedExt: String?
        switch sourceUTI {
        case "public.png": preservedExt = "png"
        case "public.jpeg": preservedExt = "jpg"
        case "public.heic": preservedExt = "heic"
        case "public.heif": preservedExt = "heif"
        default: preservedExt = nil
        }
        if let ext = preservedExt,
           CGImageSourceCreateWithData(rawData as CFData, nil) != nil {
            return (rawData, ext)
        }
        return (try Self.makePNGData(from: rawData), "png")
    }

    nonisolated private static func makePNGData(from data: Data) throws -> Data {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else {
            throw ClipboardMonitorError.invalidImageData
        }

        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(
            output,
            UTType.png.identifier as CFString,
            1,
            nil
        ) else {
            throw ClipboardMonitorError.failedToEncodePNG
        }

        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else {
            throw ClipboardMonitorError.failedToEncodePNG
        }

        return output as Data
    }

    @MainActor
    private func notifyNewItem() {
        NotificationCenter.default.post(name: .clipHistoryItemSaved, object: nil)
        onNewItem?()
        requestAiTagging()
    }

    /// 新条目入库后让标签流水线感知。幂等且异步：不阻塞采集，模型不可用/开关关闭时零开销。
    @MainActor
    private func requestAiTagging() {
        guard settings.aiTaggingEnabled else { return }
        Task { await AiTaggingService.shared.kick(core: core) }
    }
}

private enum ClipboardMonitorError: Error {
    case invalidImageData
    case failedToEncodePNG
}

/// 给 Task body 一个延迟回填 task 引用的容器：Task 创建时拿不到自己的 handle，
/// 但 body defer 时需要它来从 inflightPersists 移除——typed box 避开循环引用陷阱。
/// `finished` 与 task 的赋值时序互补，闭合「任务先完成、handle 后写入」的竞态。
@MainActor
private final class TaskBox {
    var task: Task<Void, Never>?
    var finished = false
}
